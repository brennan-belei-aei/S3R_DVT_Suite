"""Analyze Serial RF On-Off Latency summary CSV files and create two graphs.

Input CSV schema (generated by rf_onoff_scope_capture_GUI.py):
    setpoint_W, command, iteration, delta_t_ms

The program recursively reads matching non-detail CSV files from a selected folder.
Blank/invalid delta_t_ms rows are ignored in latency statistics but counted as failed
captures. Two PNG files are written to a user-selected output folder:
    1. Latency_vs_Power.png
    2. Latency_Distribution_by_Power.png
"""

from pathlib import Path
import os
import csv
import re
import tkinter as tk
from tkinter import filedialog, messagebox, ttk

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

REQUIRED_COLUMNS = {"setpoint_W", "command", "iteration", "delta_t_ms"}
COMMAND_ORDER = ("RFON", "RFOFF")
COMMAND_LABELS = {"RFON": "RF ON", "RFOFF": "RF OFF"}
COMMAND_COLORS = {"RFON": "#1f77b4", "RFOFF": "#d62728"}


def discover_csv_files(folder):
    """Find collection summary CSVs recursively, excluding details and analysis outputs."""
    files = []
    for path in Path(folder).rglob("*.csv"):
        lower = path.name.lower()
        if "_details" in lower or lower == "latency_summary.csv":
            continue
        try:
            header = pd.read_csv(path, nrows=0).columns
        except Exception:
            continue
        if REQUIRED_COLUMNS.issubset(set(header)):
            files.append(path)
    return sorted(files)


def load_data(files):
    frames = []
    for path in files:
        frame = pd.read_csv(path)
        frame = frame[list(REQUIRED_COLUMNS)].copy()
        frame["Source File"] = path.name
        frames.append(frame)
    if not frames:
        raise ValueError("No readable Serial RF On-Off Latency summary CSV files were found.")
    data = pd.concat(frames, ignore_index=True)
    data["setpoint_W"] = pd.to_numeric(data["setpoint_W"], errors="coerce")
    data["iteration"] = pd.to_numeric(data["iteration"], errors="coerce")
    data["delta_t_ms"] = pd.to_numeric(data["delta_t_ms"], errors="coerce")
    data["command"] = data["command"].astype(str).str.strip().str.upper()
    data = data[data["command"].isin(COMMAND_ORDER) & data["setpoint_W"].notna()].copy()
    if data.empty:
        raise ValueError("The CSV files contain no RFON/RFOFF rows with valid power setpoints.")
    data["Valid Measurement"] = data["delta_t_ms"].notna() & np.isfinite(data["delta_t_ms"])
    return data


def summarize(data):
    rows = []
    for (power, command), group in data.groupby(["setpoint_W", "command"], sort=True):
        valid = group.loc[group["Valid Measurement"], "delta_t_ms"]
        rows.append({
            "Power Setpoint (W)": float(power),
            "Command": command,
            "Average Latency (ms)": valid.mean() if len(valid) else np.nan,
            "Minimum Latency (ms)": valid.min() if len(valid) else np.nan,
            "Maximum Latency (ms)": valid.max() if len(valid) else np.nan,
            "Standard Deviation (ms)": valid.std(ddof=1) if len(valid) > 1 else 0.0 if len(valid) == 1 else np.nan,
            "Valid Captures": int(len(valid)),
            "Failed Captures": int((~group["Valid Measurement"]).sum()),
            "Total Captures": int(len(group)),
        })
    return pd.DataFrame(rows)


def plot_latency_vs_power(data, summary, output_path, title_suffix="", show_box_whiskers=True, show_individual_points=True):
    """Graph 1: mean latency trend, min/max range, and all valid measurements."""
    fig, ax = plt.subplots(figsize=(11, 6.5))
    offsets = {"RFON": -0.008, "RFOFF": 0.008}
    powers_all = sorted(data["setpoint_W"].dropna().unique())
    power_span = max(powers_all) - min(powers_all) if len(powers_all) > 1 else max(powers_all[0], 1)
    jitter = power_span * 0.006

    for command in COMMAND_ORDER:
        color = COMMAND_COLORS[command]
        valid = data[(data["command"] == command) & data["Valid Measurement"]]
        if valid.empty:
            continue
        if show_individual_points:
            rng = np.random.default_rng(0 if command == "RFON" else 1)
            x_scatter = valid["setpoint_W"].to_numpy(float) + rng.uniform(-jitter, jitter, len(valid))
            ax.scatter(x_scatter, valid["delta_t_ms"], color=color, alpha=0.35, s=28,
                       label=f"{COMMAND_LABELS[command]} individual captures")

        stats = summary[(summary["Command"] == command) & summary["Average Latency (ms)"].notna()].sort_values("Power Setpoint (W)")
        x = stats["Power Setpoint (W)"].to_numpy(float)
        mean = stats["Average Latency (ms)"].to_numpy(float)
        lower = mean - stats["Minimum Latency (ms)"].to_numpy(float)
        upper = stats["Maximum Latency (ms)"].to_numpy(float) - mean
        if show_box_whiskers:
            ax.errorbar(x, mean, yerr=np.vstack([lower, upper]), color=color, marker="o",
                        linewidth=2, capsize=5, markersize=7,
                        label=f"{COMMAND_LABELS[command]} average and min/max")
        else:
            ax.plot(x, mean, color=color, marker="o", linewidth=2, markersize=7,
                    label=f"{COMMAND_LABELS[command]} average")

    ax.set_title("Serial RF On-Off Latency vs Power" + title_suffix)
    ax.set_xlabel("Power Setpoint (W)")
    ax.set_ylabel("Latency (ms)")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="best")
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)


def plot_distribution(data, output_path, title_suffix="", show_box_whiskers=True):
    """Graph 2: side-by-side RF ON/RF OFF boxplots at each power setpoint."""
    valid = data[data["Valid Measurement"]].copy()
    if valid.empty:
        raise ValueError("No valid latency values are available for distribution plotting.")
    powers = sorted(valid["setpoint_W"].unique())
    positions = np.arange(len(powers), dtype=float)
    width = 0.30
    fig, ax = plt.subplots(figsize=(max(11, len(powers) * 1.25), 6.5))

    plotted = False
    for command, shift in (("RFON", -0.18), ("RFOFF", 0.18)):
        datasets, box_positions = [], []
        for pos, power in zip(positions, powers):
            values = valid.loc[(valid["command"] == command) & (valid["setpoint_W"] == power), "delta_t_ms"].to_numpy(float)
            if len(values):
                datasets.append(values)
                box_positions.append(pos + shift)
        if not datasets:
            continue
        plotted = True
        if show_box_whiskers:
            bp = ax.boxplot(datasets, positions=box_positions, widths=width, patch_artist=True,
                            showmeans=True, meanline=False,
                            meanprops={"marker": "D", "markerfacecolor": "white", "markeredgecolor": "black", "markersize": 5},
                            medianprops={"color": "black", "linewidth": 1.5})
            for box in bp["boxes"]:
                box.set_facecolor(COMMAND_COLORS[command])
                box.set_alpha(0.65)
        else:
            means = [float(np.mean(values)) for values in datasets]
            mins = [float(np.min(values)) for values in datasets]
            maxs = [float(np.max(values)) for values in datasets]
            lower = np.asarray(means) - np.asarray(mins)
            upper = np.asarray(maxs) - np.asarray(means)
            ax.errorbar(box_positions, means, yerr=np.vstack([lower, upper]),
                        fmt="o", color=COMMAND_COLORS[command], capsize=5, linewidth=2)
        ax.plot([], [], color=COMMAND_COLORS[command], linewidth=8, alpha=0.65,
                label=COMMAND_LABELS[command])

    if not plotted:
        raise ValueError("No RF ON or RF OFF latency values are available for boxplots.")
    ax.set_title(("Serial RF On-Off Latency Distribution by Power" if show_box_whiskers else "Serial RF On-Off Latency Range by Power") + title_suffix)
    ax.set_xlabel("Power Setpoint (W)")
    ax.set_ylabel("Latency (ms)")
    ax.set_xticks(positions)
    ax.set_xticklabels([f"{p:g}" for p in powers])
    ax.grid(True, axis="y", alpha=0.3)
    ax.legend(loc="best")
    fig.tight_layout()
    fig.savefig(output_path, dpi=180)
    plt.close(fig)


def analyze(input_folder, output_folder, dut_name="", show_box_whiskers=True, show_individual_points=True):
    files = discover_csv_files(input_folder)
    if not files:
        raise ValueError("No matching latency summary CSV files were found in the selected folder or its subfolders.")
    data = load_data(files)
    summary = summarize(data)
    output = Path(output_folder)
    output.mkdir(parents=True, exist_ok=True)
    suffix = f" - {dut_name.strip()}" if dut_name.strip() else ""
    graph1 = output / "Latency_vs_Power.png"
    graph2 = output / "Latency_Distribution_by_Power.png"
    plot_latency_vs_power(data, summary, graph1, suffix, show_box_whiskers, show_individual_points)
    plot_distribution(data, graph2, suffix, show_box_whiskers)
    summary.to_csv(output / "Latency_Summary.csv", index=False, quoting=csv.QUOTE_MINIMAL)
    return files, data, summary, graph1, graph2


def run_gui():
    root = tk.Tk()
    root.title("Serial RF On-Off Latency Data Analysis")
    root.minsize(760, 340)
    root.columnconfigure(0, weight=1)
    frame = ttk.Frame(root, padding=18)
    frame.grid(sticky="nsew")
    frame.columnconfigure(1, weight=1)

    unified_mode = os.environ.get("PARAMOUNT_UNIFIED_ANALYSIS_LAUNCHER") == "1"
    analysis_mode = os.environ.get("PARAMOUNT_ANALYSIS_MODE", "INDIVIDUAL").upper()
    default_input = os.environ.get("PARAMOUNT_DATASET_A_FOLDER", "").strip()
    default_output = os.environ.get("PARAMOUNT_ANALYSIS_OUTPUT_FOLDER", "").strip()
    default_dut = os.environ.get("PARAMOUNT_POWERPOINT_DUT_NAME", "").strip()
    input_var = tk.StringVar(value=default_input)
    output_var = tk.StringVar(value=default_output or (str(Path(default_input) / "Serial RF On-Off Latency Analysis") if default_input else ""))
    dut_var = tk.StringVar(value=default_dut)
    show_box_whiskers_var = tk.BooleanVar(value=True)
    show_individual_points_var = tk.BooleanVar(value=True)
    status_var = tk.StringVar(value=(
        f"Launched from Paramount Unified Data Analysis ({analysis_mode}). Review the prefilled folders, then create graphs."
        if unified_mode else "Select the folder containing the collection CSV files."
    ))

    def browse_input():
        selected = filedialog.askdirectory(parent=root, title="Select latency data folder")
        if selected:
            input_var.set(selected)
            if not output_var.get().strip():
                output_var.set(str(Path(selected) / "Serial RF On-Off Latency Analysis"))

    def browse_output():
        selected = filedialog.askdirectory(parent=root, title="Select analysis output folder")
        if selected:
            output_var.set(selected)

    ttk.Label(frame, text="Input data folder").grid(row=0, column=0, sticky="w", pady=7)
    ttk.Entry(frame, textvariable=input_var).grid(row=0, column=1, sticky="ew", pady=7, padx=8)
    ttk.Button(frame, text="Browse...", command=browse_input).grid(row=0, column=2, pady=7)
    ttk.Label(frame, text="Output folder").grid(row=1, column=0, sticky="w", pady=7)
    ttk.Entry(frame, textvariable=output_var).grid(row=1, column=1, sticky="ew", pady=7, padx=8)
    ttk.Button(frame, text="Browse...", command=browse_output).grid(row=1, column=2, pady=7)
    ttk.Label(frame, text="DUT name (optional)").grid(row=2, column=0, sticky="w", pady=7)
    ttk.Entry(frame, textvariable=dut_var).grid(row=2, column=1, sticky="ew", pady=7, padx=8)
    ttk.Checkbutton(frame, text="Use box-and-whisker plots (clear for average with min/max ranges)",
                    variable=show_box_whiskers_var).grid(row=3, column=0, columnspan=3, sticky="w", pady=7)
    ttk.Checkbutton(frame, text="Show individual measurement dots on the latency-versus-power plot",
                    variable=show_individual_points_var).grid(row=4, column=0, columnspan=3, sticky="w", pady=7)
    ttk.Label(frame, text="Creates two PNG graphs plus Latency_Summary.csv. Detail CSV files are ignored.",
              foreground="#555555").grid(row=5, column=0, columnspan=3, sticky="w", pady=(10, 4))
    ttk.Label(frame, textvariable=status_var, foreground="#333333", wraplength=700).grid(
        row=6, column=0, columnspan=3, sticky="w", pady=(10, 10))

    def start():
        try:
            input_folder = Path(input_var.get().strip())
            output_folder = Path(output_var.get().strip())
            if not input_folder.is_dir():
                raise ValueError("Select an existing input-data folder.")
            if not str(output_folder):
                raise ValueError("Select an output folder.")
            status_var.set("Analyzing CSV files and creating graphs...")
            root.update_idletasks()
            files, data, summary, graph1, graph2 = analyze(input_folder, output_folder, dut_var.get(), show_box_whiskers_var.get(), show_individual_points_var.get())
            valid_count = int(data["Valid Measurement"].sum())
            failed_count = int((~data["Valid Measurement"]).sum())
            message = (f"Analysis complete. Read {len(files)} CSV file(s), {valid_count} valid measurements, "
                       f"and {failed_count} failed/blank measurements.\n\nCreated:\n{graph1}\n{graph2}")
            status_var.set(message)
            messagebox.showinfo("Analysis complete", message, parent=root)
        except Exception as exc:
            status_var.set(str(exc))
            messagebox.showerror("Analysis failed", str(exc), parent=root)

    buttons = ttk.Frame(frame)
    buttons.grid(row=7, column=0, columnspan=3, sticky="e", pady=(12, 0))
    ttk.Button(buttons, text="Create Graphs", command=start).pack(side="left", padx=5)
    ttk.Button(buttons, text="Close", command=root.destroy).pack(side="left", padx=5)
    root.mainloop()


if __name__ == "__main__":
    run_gui()
